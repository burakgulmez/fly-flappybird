"""Write paper/numbers.tex: every number in the paper as a macro read from results/."""
import glob
import json
import os

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = os.path.join(ROOT, "results")
circ = json.load(open(os.path.join(R, "circuit_stats.json")))
runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(R, "runs", "seed*", "summary.json")))]
cfg = json.load(open(os.path.join(R, "runs", "seed0", "config.json")))
ref = pd.read_csv(os.path.join(R, "reference_agents.csv")).set_index("agent")
les = pd.read_csv(os.path.join(R, "lesion.csv"))

def fmt(x, d=1):
    return f"{x:.{d}f}"

broken = les[(les.condition != "intact") & (les.mean_pipes < 50)]
m = {
    "Neurons": circ["neurons"], "Inputs": circ["inputs"], "NLPLCtwo": circ["input_types"]["LPLC2"],
    "NLCfour": circ["input_types"]["LC4"], "Intermediates": circ["intermediates"], "Outputs": circ["outputs"],
    "Edges": circ["edges"], "ExcPct": fmt(100 * circ["frac_excitatory_edges"]),
    "NAch": circ["nt_edges"]["ACH"], "NGaba": circ["nt_edges"]["GABA"], "NGlut": circ["nt_edges"]["GLUT"],
    "NParams": runs[0]["n_params"], "NSeeds": len(runs), "TestGames": cfg["test_games"],
    "BudgetFrames": f"{cfg['budget_frames']:,}".replace(",", "{,}"),
    "MeanPipesAll": fmt(np.mean([r["test_mean_pipes"] for r in runs])),
    "WinRateAll": fmt(100 * np.mean([r["test_win_rate"] for r in runs]), 0),
    "GensMin": min(r["generations"] for r in runs), "GensMax": max(r["generations"] for r in runs),
    "TrainTimeMean": fmt(np.mean([r["train_time_s"] for r in runs]), 0),
    "TrainTimeMax": fmt(max(r["train_time_s"] for r in runs), 0),
    "HeurMean": fmt(ref.loc["heuristic", "mean_pipes"]), "HeurWin": fmt(100 * ref.loc["heuristic", "win_rate"], 0),
    "RandMean": fmt(ref.loc["random_10pct_flap", "mean_pipes"], 2),
    "EdgesDirect": circ["edges_input_to_output"], "EdgesInMid": circ["edges_input_to_intermediate"],
    "EdgesMidOut": circ["edges_intermediate_to_output"],
    "LesBrokenCount": len(broken), "LesConditions": les.condition.nunique() - 1,
}
with open(os.path.join(ROOT, "paper", "numbers.tex"), "w") as f:
    f.write("% generated by paper/make_numbers.py from results/ -- do not edit\n")
    for k, v in m.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    # lesion table rows
    piv = les.pivot(index="condition", columns="seed", values="mean_pipes")
    order = ["intact", "all intermediates", "LC4 inputs", "LPLC2 inputs"] + [c for c in piv.index if c.endswith("output")]
    rows = "\n".join(f"{c} & " + " & ".join(fmt(v) for v in piv.loc[c].values) + r" \\" for c in order)
    f.write("\\newcommand{\\LesionRows}{" + rows.replace("\n", " ") + "}\n")
print(open(os.path.join(ROOT, "paper", "numbers.tex")).read())
